/** Generate the fictional example data in examples/data (no real customers). */
import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { DatabaseSync } from "node:sqlite";

const dir = "examples/data";
mkdirSync(dir, { recursive: true });

// Deterministic pseudo-random generator so the examples never change.
let seed = 42;
const rand = () => {
  seed = (seed * 1103515245 + 12345) % 2 ** 31;
  return seed / 2 ** 31;
};
const pick = <T>(xs: T[]): T => xs[Math.floor(rand() * xs.length)] as T;

const cities = ["Lisbon", "Porto", "Braga", "Coimbra", "Faro"];
const products = [
  ["Starter", 29],
  ["Growth", 79],
  ["Enterprise", 249],
] as const;

const customers = Array.from({ length: 40 }, (_, i) => ({
  id: i + 1,
  name: `Customer ${String(i + 1).padStart(2, "0")}`,
  city: pick(cities),
  signup: `2026-0${1 + Math.floor(rand() * 9)}-${String(1 + Math.floor(rand() * 28)).padStart(2, "0")}`,
}));

rmSync(`${dir}/shop.db`, { force: true });
const db = new DatabaseSync(`${dir}/shop.db`);
db.exec(`
  CREATE TABLE customers (id INTEGER PRIMARY KEY, name TEXT NOT NULL, city TEXT, signup_date TEXT);
  CREATE TABLE orders (id INTEGER PRIMARY KEY, customer_id INTEGER REFERENCES customers(id),
                       plan TEXT, amount_eur REAL, ordered_at TEXT);
`);
const insertCustomer = db.prepare("INSERT INTO customers VALUES (?, ?, ?, ?)");
for (const c of customers) insertCustomer.run(c.id, c.name, c.city, c.signup);
const insertOrder = db.prepare("INSERT INTO orders VALUES (?, ?, ?, ?, ?)");
const csv = ["order_id,customer_id,city,plan,amount_eur,ordered_at,paid"];
for (let id = 1; id <= 200; id++) {
  const c = pick(customers);
  const [plan, price] = pick([...products]);
  const date = `2026-${String(1 + Math.floor(rand() * 10)).padStart(2, "0")}-${String(1 + Math.floor(rand() * 28)).padStart(2, "0")}`;
  insertOrder.run(id, c.id, plan, price, date);
  const paid = rand() > 0.08 ? "true" : "false";
  const amount = rand() > 0.03 ? String(price) : ""; // a few missing values on purpose
  csv.push(`${id},${c.id},${c.city},${plan},${amount},${date},${paid}`);
}
db.close();
writeFileSync(`${dir}/orders.csv`, `${csv.join("\n")}\n`);
writeFileSync(
  `${dir}/README.md`,
  "# Example data\n\nFictional customers and orders for a SaaS company, generated by `npm run examples`.\n",
);
console.log("wrote examples/data/{shop.db,orders.csv,README.md}");
